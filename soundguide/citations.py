"""Validate model drafts and construct citations from authoritative evidence."""

# ruff: noqa: RUF001
import re
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field

from soundguide.evidence import EvidenceChunk


class Reference(BaseModel):
    """A model may select existing evidence labels, never invent source text or URLs."""

    model_config = ConfigDict(extra="forbid")
    evidence_id: str = Field(min_length=2, max_length=4)


class Claim(BaseModel):
    """One generated statement with one or more supporting evidence selections."""

    model_config = ConfigDict(extra="forbid")
    text: str = Field(min_length=1, max_length=240)
    evidence: list[Reference] = Field(min_length=1, max_length=3)


class Draft(BaseModel):
    """Provider output is untrusted until validated against retrieved evidence."""

    model_config = ConfigDict(extra="forbid")
    status: Literal["answered", "insufficient_evidence", "clarification_needed"]
    claims: list[Claim] = Field(max_length=6)
    clarification: str | None = Field(default=None, max_length=200)


class InvalidAnswerError(ValueError):
    """Invalid/truncated output must not be shown as a supported answer."""


def render_unanswered(draft: Draft) -> dict:
    """Validate clarification and refusal responses separately from citations."""
    if draft.claims:
        raise InvalidAnswerError("Non-answer contains claims")
    if draft.status == "clarification_needed":
        if (
            not draft.clarification
            or not draft.clarification.strip()
            or re.search(r"https?://|\[[0-9]+\]", draft.clarification)
        ):
            raise InvalidAnswerError("Missing clarification question")
        return {
            "status": draft.status,
            "answer": draft.clarification,
            "citations": [],
        }
    return {
        "status": "insufficient_evidence",
        "answer": "当前检索到的官方资料不足以可靠回答这个问题。这不代表完整手册中一定没有相关说明。",
        "citations": [],
    }


def citation_from(hit: EvidenceChunk, model: str, number: int) -> dict:
    """Build a public citation exclusively from the retrieved chunk."""
    metadata = hit["metadata"]
    return {
        "number": number,
        "chunk_id": hit["id"],
        "quote": hit["content"],
        "model": model,
        "page": metadata.get("page"),
        "section_title": metadata.get("section_title"),
        "document_version": metadata["document_version"],
        "format": metadata.get("format", "pdf"),
        "machine_translated": metadata.get("machine_translated", False),
        "content_sha256": metadata["content_sha256"],
        "url": hit["citation_url"],
    }


def claim_evidence(
    claim: Claim, evidence: dict[str, EvidenceChunk], model: str
) -> list[EvidenceChunk]:
    """Resolve references without trusting text or links generated by the model."""
    if not claim.text.strip() or re.search(r"https?://|\[[0-9]+\]", claim.text):
        raise InvalidAnswerError("The provider invented links or citation labels")
    hits = []
    for reference in claim.evidence:
        hit = evidence.get(reference.evidence_id)
        if not hit or hit["metadata"]["model"] != model or not hit["content"].strip():
            raise InvalidAnswerError(
                "Citation does not refer to eligible retrieved evidence"
            )
        hits.append(hit)
    return hits


def render(draft: Draft, hits: list[EvidenceChunk], model: str) -> dict:
    """Assign stable first-seen citation numbers and deduplicate within each claim."""
    if draft.status != "answered":
        return render_unanswered(draft)
    if not draft.claims or draft.clarification:
        raise InvalidAnswerError("Answered output has no supported claims")
    evidence = {f"E{i}": hit for i, hit in enumerate(hits, 1)}
    citations = []
    citation_numbers_by_chunk_id: dict[str, int] = {}
    parts = []
    for claim in draft.claims:
        numbers: list[int] = []
        for hit in claim_evidence(claim, evidence, model):
            chunk_id = hit["id"]
            if chunk_id not in citation_numbers_by_chunk_id:
                number = len(citations) + 1
                citation_numbers_by_chunk_id[chunk_id] = number
                citations.append(citation_from(hit, model, number))
            numbers.append(citation_numbers_by_chunk_id[chunk_id])
        labels = "".join(f"[{number}]" for number in dict.fromkeys(numbers))
        parts.append(claim.text + labels)
    return {"status": "answered", "answer": "\n".join(parts), "citations": citations}
